/**
 * 翻译角色名称（支持 ID 或 英文名）
 */
export function charNameZh(idOrName: string): string {
  if (!idOrName) return "";
  const trimmed = idOrName.trim();
  const lower = trimmed.toLowerCase();
  if (CHARACTER_NAME_ZH[lower]) return CHARACTER_NAME_ZH[lower];
  if (CHARACTER_ENGLISH_TO_ZH[trimmed]) return CHARACTER_ENGLISH_TO_ZH[trimmed];

  // 针对形如 "Traveler", "traveler-anemo", "Traveler (Anemo Traveler)" 等的匹配
  if (lower.startsWith("traveler") || lower.startsWith("旅行者")) {
    if (lower.includes("anemo") || lower.includes("风")) return "旅行者 (风)";
    if (lower.includes("geo") || lower.includes("岩")) return "旅行者 (岩)";
    if (lower.includes("electro") || lower.includes("雷")) return "旅行者 (雷)";
    if (lower.includes("dendro") || lower.includes("草")) return "旅行者 (草)";
    if (lower.includes("hydro") || lower.includes("水")) return "旅行者 (水)";
    if (lower.includes("pyro") || lower.includes("火")) return "旅行者 (火)";
    return "旅行者";
  }

  return trimmed;
}

