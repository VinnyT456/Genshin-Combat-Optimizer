export function tierReasonZh(reason?: string): string | undefined {
  if (!reason) return undefined;
  if (reason.includes("Damage kit sourced from datamined data")) {
    return "全等级天赋倍率、属性成长曲线、冷却时间与能量消耗。固有天赋与命之座暂未作为机读参数实装。";
  }
  if (reason.includes("Burst infusion is not modelled")) {
    return "元素爆发附魔暂未实装。";
  }
  if (reason.includes("Stack-gated behaviour is not simulated")) {
    return "层数叠加机制暂未实装。";
  }
  if (reason.includes("Stacks are not simulated")) {
    return "层数机制暂未实装。";
  }
  // A MISS RETURNS `undefined`, never the source string.
  //
  // This used to `return reason`. The generator's wording then changed to
  // "Damage kit sourced (per-level talent tables, ..." and zero of the 132 live
  // reasons matched any pattern above, so every caveat in a zh-CN product
  // rendered as a ~250-character English engineering paragraph naming internal
  // field names. TypeScript could not catch it: the fallback is a valid string.
  //
  // Falling through to English is strictly worse than saying nothing, so this
  // now fails closed. Callers must treat `undefined` as "no translated reason"
  // and render nothing rather than substituting the English source.
  //
  // This is a STOPGAP. Substring-matching generated English prose cannot be
  // kept correct — the generator owns the wording, the UI owns the match, and
  // neither knows about the other. The durable fix is a structured
  // `reasonCode` on the provenance row, routed to the data owner.
  return undefined;
}

